import { mkdir, readFile, stat, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join } from "node:path";

export const GITHUB_GATE_WORKFLOW_FILE = ".github/workflows/context-factory-gate.yml";
export const GITHUB_GATE_MARKER = "Context Factory Strict Conformance Gate";

/**
 * Renders the GitHub Actions workflow YAML for strict Context Factory conformance.
 *
 * @param {{
 *   submodulePath?: string,
 *   packageManager?: string,
 *   nodeVersion?: string,
 *   testCommand?: string | null,
 *   lintCommand?: string | null,
 * }} options
 * @returns {string}
 */
export function renderGitHubWorkflow(options = {}) {
  const {
    submodulePath = ".context-factory",
    packageManager = "npm",
    nodeVersion = "22",
    testCommand = null,
    lintCommand = null,
  } = options;

  const hostLintSection = lintCommand
    ? `      - name: Host Lint
        run: ${lintCommand}`
    : `      # Host lint: unconfigured (skipped)`;

  const hostTestSection = testCommand
    ? `      - name: Host Tests
        run: ${testCommand}`
    : `      # Host tests: unconfigured (skipped)`;

  return `# ${GITHUB_GATE_MARKER}
# Generated by Context Factory CLI (opt-in quality gate)
name: Context Factory Conformance Gate

on:
  pull_request:
  push:
    branches: [main, master]

permissions:
  contents: read

jobs:
  conformance-gate:
    name: Conformance Verification
    runs-on: ubuntu-latest
    steps:
      - name: Checkout repository (with submodules)
        uses: actions/checkout@v4
        with:
          submodules: recursive
          fetch-depth: 0

      - name: Setup Node.js
        uses: actions/setup-node@v4
        with:
          node-version: ${nodeVersion}

      - name: Verify Context Factory Health
        run: |
          if [ -f "${submodulePath}/scripts/context.mjs" ]; then
            node ${submodulePath}/scripts/context.mjs doctor
          elif [ -f "${submodulePath}/app/cli/bin/context-cli.mjs" ]; then
            node ${submodulePath}/app/cli/bin/context-cli.mjs doctor
          else
            echo "Context Factory submodule not found at ${submodulePath}"
            exit 1
          fi

${hostLintSection}

${hostTestSection}

      - name: Execute Code Conformance Evaluation
        run: |
          mkdir -p .context-runs
          if [ -f "${submodulePath}/app/cli/bin/context-cli.mjs" ]; then
            node ${submodulePath}/app/cli/bin/context-cli.mjs conform "ci-gate" --out .context-runs/conformance-report.json --json
          elif [ -f "${submodulePath}/scripts/context.mjs" ]; then
            node ${submodulePath}/scripts/context.mjs conform "ci-gate" --out .context-runs/conformance-report.json --json
          fi

      - name: Verify Conformance Report Receipt
        run: |
          if [ -f "${submodulePath}/app/cli/bin/context-cli.mjs" ]; then
            node ${submodulePath}/app/cli/bin/context-cli.mjs conform verify .context-runs/conformance-report.json
          elif [ -f "${submodulePath}/scripts/context.mjs" ]; then
            node ${submodulePath}/scripts/context.mjs conform:verify .context-runs/conformance-report.json
          fi

      - name: Upload Conformance Report Artifact
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: context-conformance-report
          path: .context-runs/
          if-no-files-found: ignore
`;
}

/**
 * Returns copyable guidance for unsupported CI providers (AC-04).
 *
 * @param {string} provider
 * @param {{ submodulePath?: string }} options
 * @returns {{
 *   supported: false,
 *   provider: string,
 *   explanation: string,
 *   commands: string[]
 * }}
 */
export function getUnsupportedCiGuidance(provider = "generic", options = {}) {
  const { submodulePath = ".context-factory" } = options;

  return {
    supported: false,
    provider,
    explanation: `Automated workflow file generation is currently supported for GitHub Actions. For ${provider}, copy the following pipeline commands:`,
    commands: [
      "git submodule update --init --recursive",
      `node ${submodulePath}/scripts/context.mjs doctor`,
      `node ${submodulePath}/app/cli/bin/context-cli.mjs conform "ci-gate" --out .context-runs/conformance-report.json`,
      `node ${submodulePath}/app/cli/bin/context-cli.mjs conform verify .context-runs/conformance-report.json`,
    ],
  };
}

/**
 * Probes the status of the GitHub Actions workflow in the target directory.
 *
 * @param {{ targetDir?: string }} options
 * @returns {Promise<{
 *   status: "not_installed" | "installed" | "conflict",
 *   workflowPath: string,
 *   isContextFactory: boolean,
 *   error?: string
 * }>}
 */
export async function getWorkflowStatus(options = {}) {
  const { targetDir = process.cwd() } = options;
  const workflowPath = join(targetDir, GITHUB_GATE_WORKFLOW_FILE);

  if (!existsSync(workflowPath)) {
    return {
      status: "not_installed",
      workflowPath,
      isContextFactory: false,
    };
  }

  try {
    const content = await readFile(workflowPath, "utf8");
    const isContextFactory = content.includes(GITHUB_GATE_MARKER);
    return {
      status: isContextFactory ? "installed" : "conflict",
      workflowPath,
      isContextFactory,
    };
  } catch (readError) {
    return {
      status: "conflict",
      workflowPath,
      isContextFactory: false,
      error: readError.message,
    };
  }
}

/**
 * Safely installs or updates the GitHub Actions quality gate with idempotence and non-clobbering guarantees.
 *
 * @param {{
 *   targetDir?: string,
 *   submodulePath?: string,
 *   packageManager?: string,
 *   nodeVersion?: string,
 *   testCommand?: string | null,
 *   lintCommand?: string | null,
 *   dryRun?: boolean,
 *   force?: boolean,
 *   preview?: boolean
 * }} options
 * @returns {Promise<{
 *   success: boolean,
 *   action: "preview" | "created" | "already_installed" | "overwritten" | "conflict" | "error",
 *   workflowPath: string,
 *   dryRun?: boolean,
 *   conflict?: boolean,
 *   content?: string,
 *   status?: string,
 *   error?: string
 * }>}
 */
export async function installGitHubWorkflow(options = {}) {
  const {
    targetDir = process.cwd(),
    submodulePath = ".context-factory",
    packageManager = "npm",
    nodeVersion = "22",
    testCommand = null,
    lintCommand = null,
    dryRun = false,
    force = false,
    preview = false,
  } = options;

  const isPreview = Boolean(dryRun || preview);
  const workflowPath = join(targetDir, GITHUB_GATE_WORKFLOW_FILE);
  const workflowDir = dirname(workflowPath);
  const currentStatus = await getWorkflowStatus({ targetDir });
  const content = renderGitHubWorkflow({
    submodulePath,
    packageManager,
    nodeVersion,
    testCommand,
    lintCommand,
  });

  if (isPreview) {
    return {
      success: true,
      dryRun: true,
      action: "preview",
      workflowPath,
      status: currentStatus.status,
      content,
    };
  }

  if (currentStatus.status === "installed" && !force) {
    return {
      success: true,
      action: "already_installed",
      workflowPath,
    };
  }

  if (currentStatus.status === "conflict" && !force) {
    return {
      success: false,
      conflict: true,
      action: "conflict",
      workflowPath,
      error: `An existing unrelated workflow file was found at "${workflowPath}". Context Factory will not overwrite existing workflows without --force.`,
    };
  }

  await mkdir(workflowDir, { recursive: true });

  if (force) {
    await writeFile(workflowPath, content, "utf8");
    return {
      success: true,
      action: currentStatus.status === "not_installed" ? "created" : "overwritten",
      workflowPath,
    };
  }

  try {
    // Exclusive write to prevent race condition clobbering
    await writeFile(workflowPath, content, { encoding: "utf8", flag: "wx" });
    return {
      success: true,
      action: "created",
      workflowPath,
    };
  } catch (writeError) {
    if (writeError.code === "EEXIST") {
      const recheck = await readFile(workflowPath, "utf8").catch(() => "");
      if (recheck.includes(GITHUB_GATE_MARKER)) {
        return {
          success: true,
          action: "already_installed",
          workflowPath,
        };
      }
      return {
        success: false,
        conflict: true,
        action: "conflict",
        workflowPath,
        error: `A concurrent process wrote an existing workflow file at "${workflowPath}".`,
      };
    }
    throw writeError;
  }
}
